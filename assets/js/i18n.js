  if(window.FAQ_I18N){ Object.assign(I18N.en, window.FAQ_I18N.en); Object.assign(I18N.th, window.FAQ_I18N.th); }

  const LANG_KEY = 'wb.lang';
  const langButtons = Array.prototype.slice.call(document.querySelectorAll('.lang button'));
  const metaDesc = document.querySelector('meta[name="description"]');

  function setMeta(sel, attr, value){
    const el = document.querySelector(sel);
    if(el) el.setAttribute(attr, value);
  }

  let lang = 'en';

  function dict(){
    return I18N[lang] || I18N.en;
  }

  function apply(next){
    lang = (next === 'th') ? 'th' : 'en';
    const t = dict();
    document.documentElement.lang = lang;
    const titleKey = document.body.dataset.titleKey || 'meta.title';
    document.title = t[titleKey];
    if(metaDesc) metaDesc.setAttribute('content', t['meta.description']);
    setMeta('meta[property="og:title"]', 'content', t[titleKey]);
    setMeta('meta[property="og:description"]', 'content', t['meta.description']);
    setMeta('meta[name="twitter:title"]', 'content', t[titleKey]);
    setMeta('meta[name="twitter:description"]', 'content', t['meta.description']);
    setMeta('meta[property="og:locale"]', 'content', lang === 'th' ? 'th_TH' : 'en_US');
    Array.prototype.forEach.call(document.querySelectorAll('[data-i18n]'), (el) => {
      const key = el.getAttribute('data-i18n');
      if(Object.prototype.hasOwnProperty.call(t, key)) el.textContent = t[key];
    });
    Array.prototype.forEach.call(document.querySelectorAll('[data-i18n-aria]'), (el) => {
      const key = el.getAttribute('data-i18n-aria');
      if(Object.prototype.hasOwnProperty.call(t, key)) el.setAttribute('aria-label', t[key]);
    });
    langButtons.forEach((btn) => {
      btn.setAttribute('aria-pressed', btn.getAttribute('data-lang') === lang ? 'true' : 'false');
    });
  }

  let swapTimer = 0;
  function set(next){
    if(next === lang) return;
    document.body.classList.add('is-swapping');
    window.clearTimeout(swapTimer);
    swapTimer = window.setTimeout(() => {
      apply(next);
      window.PortfolioCore.store.set(LANG_KEY, next);
      document.body.classList.remove('is-swapping');
    }, 120);
  }

  function init(){
    langButtons.forEach((btn) => {
      btn.addEventListener('click', () => set(btn.getAttribute('data-lang')));
    });
  }

  return { init, apply, set, dict, get lang(){ return lang; } };
