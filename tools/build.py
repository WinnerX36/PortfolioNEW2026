#!/usr/bin/env python3
"""Generate FAQ output and the Thai homepage from their sources.

Sources:  data/faq.json, index.html (English page), assets/js/i18n.js (Thai strings)
Outputs:  FAQ section + head block in index.html, assets/js/faq-i18n.js,
          FAQ block in llms-full.txt, th/index.html

Run after editing any source:  python3 tools/build.py
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://wuttiphongbutta.netlify.app"


def read(name):
    return (ROOT / name).read_text(encoding="utf-8")


def write(name, text):
    path = ROOT / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def between(text, tag, body, open_="<!-- {}:start -->", close="<!-- {}:end -->"):
    """Replace whatever sits between a start/end marker pair."""
    start, end = open_.format(tag), close.format(tag)
    if text.count(start) != 1 or text.count(end) != 1:
        raise SystemExit(f"marker {tag} missing or duplicated")
    a = text.index(start) + len(start)
    b = text.index(end)
    return text[:a] + "\n" + body + text[b:]


def thai_strings():
    src = read("assets/js/i18n.js")
    block = src[src.index("    th: {"):src.index("\n  };")]
    out = {}
    for m in re.finditer(r"^\s*'([\w.]+)':\s*'(.*)',?\s*$", block, re.M):
        out[m.group(1)] = m.group(2).replace("\\'", "'")
    return out


def faq_html(faq, lang):
    title = "FAQ" if lang == "en" else "คำถามที่พบบ่อย"
    items = []
    for i, f in enumerate(faq, 1):
        q, a = html.escape(f[lang]["q"]), html.escape(f[lang]["a"])
        items.append(
            f'        <details class="faq-item">\n'
            f'          <summary data-i18n="faq.q{i}">{q}</summary>\n'
            f'          <p data-i18n="faq.a{i}">{a}</p>\n'
            f'        </details>'
        )
    return (
        '  <section class="panel" id="faq" data-od-id="faq-section">\n'
        '    <div class="wrap">\n'
        '      <div class="section-head" data-reveal>\n'
        '        <span class="num">06</span>\n'
        f'        <h2 data-i18n="faq.title">{title}</h2>\n'
        '      </div>\n'
        '      <div class="faq-list">\n'
        + "\n".join(items) + "\n"
        '      </div>\n'
        '    </div>\n'
        '  </section>\n  '
    )


def head_block(faq, lang):
    ld = {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "inLanguage": "en" if lang == "en" else "th",
        "mainEntity": [
            {"@type": "Question", "name": f[lang]["q"],
             "acceptedAnswer": {"@type": "Answer", "text": f[lang]["a"]}}
            for f in faq
        ],
    }
    return (
        f'<link rel="alternate" hreflang="en" href="{SITE}/" />\n'
        f'<link rel="alternate" hreflang="th" href="{SITE}/th/" />\n'
        f'<link rel="alternate" hreflang="x-default" href="{SITE}/" />\n'
        '<script type="application/ld+json">\n'
        + json.dumps(ld, ensure_ascii=False, indent=2)
        + "\n</script>\n"
    )


def build():
    faq = json.loads(read("data/faq.json"))

    # 1. English page: FAQ section + head block
    en = read("index.html")
    en = between(en, "faq", faq_html(faq, "en"))
    en = between(en, "head", head_block(faq, "en"))
    write("index.html", en)

    # 2. FAQ strings for the in-page EN/TH switch
    strings = {lang: {"faq.title": "FAQ" if lang == "en" else "คำถามที่พบบ่อย"} for lang in ("en", "th")}
    for i, f in enumerate(faq, 1):
        for lang in ("en", "th"):
            strings[lang][f"faq.q{i}"] = f[lang]["q"]
            strings[lang][f"faq.a{i}"] = f[lang]["a"]
    write("assets/js/faq-i18n.js",
          "/* Generated by tools/build.py from data/faq.json. Do not edit. */\n"
          f"window.FAQ_I18N = {json.dumps(strings, ensure_ascii=False, indent=2)};\n")

    # 3. llms-full.txt FAQ block (both languages)
    lines = ["## FAQ", ""]
    for f in faq:
        lines += [f"### {f['en']['q']}", f["en"]["a"], ""]
    for f in faq:
        lines += [f"### {f['th']['q']}", f["th"]["a"], ""]
    write("llms-full.txt", between(read("llms-full.txt"), "faq", "\n".join(lines)))

    # 4. Thai page: same markup, Thai text written into the HTML
    th = thai_strings()
    th.update(strings["th"])
    page = en

    def fill(m):
        key = m.group(2)
        return m.group(1) + html.escape(th[key], quote=False) if key in th else m.group(0)

    page = re.sub(r'(<[^>]*\bdata-i18n="([\w.]+)"[^>]*>)[^<]*', fill, page)
    page = re.sub(
        r'(\bdata-i18n-aria="([\w.]+)"[^>]*?)aria-label="[^"]*"',
        lambda m: m.group(0) if m.group(2) not in th else m.group(1) + f'aria-label="{html.escape(th[m.group(2)])}"',
        page,
    )
    title, desc = html.escape(th["meta.title"]), html.escape(th["meta.description"])
    page = re.sub(r"<title>.*?</title>", f"<title>{title}</title>", page, count=1)
    page = re.sub(r'(<meta (?:name|property)="(?:og:|twitter:)?title" content=")[^"]*', lambda m: m.group(1) + title, page)
    page = re.sub(r'(<meta (?:name|property)="(?:og:|twitter:)?description" content=")[^"]*', lambda m: m.group(1) + desc, page)
    page = page.replace('<html lang="en">', '<html lang="th" data-lang="th">', 1)
    page = page.replace('property="og:locale" content="en_US"', 'property="og:locale" content="th_TH"', 1)
    page = page.replace('property="og:locale:alternate" content="th_TH"', 'property="og:locale:alternate" content="en_US"', 1)
    page = page.replace(f'<link rel="canonical" href="{SITE}/" />', f'<link rel="canonical" href="{SITE}/th/" />', 1)
    page = between(page, "head", head_block(faq, "th"))
    # the Thai page lives one folder down
    page = re.sub(r'\b(href|src)="(assets/|about\.html|index\.html)', r'\1="../\2', page)
    page = page.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by tools/build.py from index.html. Do not edit. -->", 1)
    write("th/index.html", page)

    print("built: index.html, assets/js/faq-i18n.js, llms-full.txt, th/index.html")


if __name__ == "__main__":
    build()
